/**
 * Each German Land's school vacations, as the Land publishes them (MON-13).
 *
 * German school holidays are Land law, and the Länder stagger their summer breaks under the KMK's
 * long-term arrangement, so there is no nationwide period: [GermanHolidays] without a Land draws
 * none, and a parent who names their Land gets that Land's list through
 * [GermanHolidays.forRegion].
 *
 * **Source:** the OpenHolidays dataset (github.com/openpotato/openholidaysapi.data, ODbL 1.0),
 * whose German school holidays follow the Länder's published lists that the KMK Ferienkalender
 * collects. A sample was checked against the KMK calendar and km.bayern.de before this table was
 * written; `SchoolVacationReferenceTest` holds every row, and both names, to the fixture
 * `tools/generate-school-vacation-fixture.py` writes from a pinned commit of the dataset.
 *
 * **Coverage:** every period starting on or after 1 September 2025 (school year 2025/26), up to
 * whatever the Land had published at that commit — the summer of 2030 for most, spring 2031 for
 * Schleswig-Holstein. Nothing is extrapolated; a year past the end simply draws no vacation.
 *
 * **What is in, and what is not:**
 * - The Land-wide single school-free days each Land lists itself (Buß- und Bettag in Bavaria,
 *   the day after Ascension in several Länder, …) are in: they are Land-wide and in the Land's
 *   own list, and a parent planning a handover needs them as much as a week's break.
 * - Mecklenburg-Western Pomerania publishes general and vocational schools separately; this is
 *   **general schools** (`MV-ABS`). A child at a vocational school is not who a custody calendar
 *   is usually about.
 * - Schleswig-Holstein's **island exceptions** (Sylt, Föhr, Amrum, Helgoland, the Halligen) are
 *   not drawn: a Land setting cannot say that a family lives on an island.
 * - Days a *school* chooses for itself (the "bewegliche Ferientage" of several Länder) are not in
 *   any Land list and cannot be drawn by any table.
 */
