package com.coparently.app.wire

import kotlinx.io.buffered
import kotlinx.io.files.Path
import kotlinx.io.files.SystemFileSystem
import kotlinx.io.readString
import kotlinx.io.writeString

/**
 * One wire fixture file.
 *
 * The file is a JSON object with `about` (one sentence: who writes this shape and why it is
 * here), `document` (the Firestore document), `reads` (what this build must read from it — see
 * [WireContract.read] — or null when it must skip it, with `skipped` saying why) and optionally
 * `notPreserved` (dotted paths a read-then-write loses, each with the reason).
 *
 * @property file The file, for messages.
 * @property collection The directory it sits in, which names its [WireContract].
 * @property current True for `wire/current/`: what *this* build writes, regenerated rather than
 *   hand-written, and read by the previous build in CI.
 */
internal data class WireFixture(
    val file: Path,
    val collection: String,
    val current: Boolean,
    val about: String,
    val document: Map<String, Any?>,
    val reads: Map<String, Any?>?,
    val skipped: String?,
    val notPreserved: Map<String, String>
) {
    /** `current/events/repository-save` or `events/older-build`, for test names. */
    val name: String
        get() = (if (current) "current/" else "") + "$collection/${file.name.removeSuffix(".json")}"

    override fun toString(): String = name
}

/**
 * The module's contracts, as the harness runs them. Each module that runs wire tests declares one
 * object, `WireContracts`, implementing this: `:shared-data` for the contracts whose writers live
 * there, the app for every contract.
 */
internal interface WireSuite {

    /** The contracts this module runs. */
    val all: List<WireContract>

    /**
     * Whether [all] is every contract the build has, so a fixture directory with none of them is an
     * orphan. Only the app's list is, until every writer has moved.
     */
    val complete: Boolean

    /** Runs [block] as the reading phone would: the app's contracts read in UTC. */
    fun <T> inReaderZone(block: () -> T): T

    /** The contract for [collection], or null when this module has none. */
    fun forCollection(collection: String): WireContract? = all.firstOrNull { it.collection == collection }
}

/**
 * Where the wire fixtures live, and how they are read.
 *
 * `app/src/test/resources/wire/<collection>/<case>.json` holds documents *other* builds write —
 * older ones with keys missing, newer ones with keys and codec versions this build does not know —
 * written by hand. `wire/current/<collection>/<case>.json` holds what *this* build writes,
 * regenerated by `CurrentWireFixturesTest`. Read from the source tree through kotlinx-io, on the
 * JVM and the iOS simulator alike, from [WireFixtureLocation.ROOT], so that test can rewrite them
 * and the CI step that runs the previous build's `WireContractTest` over this build's `current/`
 * only has to copy a directory.
 */
internal object WireFixtures {

    /** The environment variable that makes `CurrentWireFixturesTest` rewrite `wire/current/`. */
    const val UPDATE_ENV = "UPDATE_WIRE_FIXTURES"

    /** The fixture root, `app/src/test/resources/wire`. */
    val root: Path get() = Path(WireFixtureLocation.ROOT)

    /** `wire/current/`. */
    val currentRoot: Path get() = Path(root, "current")

    /** Every fixture, hand-written and current, sorted by name. */
    fun all(): List<WireFixture> {
        val handWritten = directories(root)
            .filter { it.name != "current" }
            .flatMap { dir -> jsonFiles(dir).map { load(it, dir.name, current = false) } }
        val current = directories(currentRoot)
            .flatMap { dir -> jsonFiles(dir).map { load(it, dir.name, current = true) } }
        return (handWritten + current).sortedBy { it.name }
    }

    /** One fixture file, parsed. */
    @Suppress("UNCHECKED_CAST")
    fun load(file: Path, collection: String, current: Boolean): WireFixture {
        val json = WireJson.parse(read(file)) as? Map<String, Any?>
            ?: error("$file is not a JSON object")
        return WireFixture(
            file = file,
            collection = collection,
            current = current,
            about = json["about"] as? String ?: error("$file has no \"about\""),
            document = json["document"] as? Map<String, Any?> ?: error("$file has no \"document\" object"),
            reads = json["reads"] as? Map<String, Any?>,
            skipped = json["skipped"] as? String,
            notPreserved = (json["notPreserved"] as? Map<String, Any?>).orEmpty()
                .mapValues { (_, reason) -> reason.toString() }
        )
    }

    /** The JSON object a current fixture file holds for [write], as `CurrentWireFixturesTest` writes it. */
    fun currentJson(write: CurrentWrite, reads: Map<String, Any?>?): Map<String, Any?> = buildMap {
        put("about", write.about)
        put("document", write.document)
        put("reads", reads)
        if (write.olderBuildsMayDrop.isNotEmpty()) put("notPreserved", write.olderBuildsMayDrop)
    }

    /** The directories directly under [dir], or none when it does not exist. */
    fun directories(dir: Path): List<Path> =
        list(dir).filter { SystemFileSystem.metadataOrNull(it)?.isDirectory == true }

    /** The `.json` files directly under [dir], or none when it does not exist. */
    fun jsonFiles(dir: Path): List<Path> =
        list(dir).filter { it.name.endsWith(".json") && SystemFileSystem.metadataOrNull(it)?.isRegularFile == true }

    /** [file]'s text. */
    fun read(file: Path): String = SystemFileSystem.source(file).buffered().use { it.readString() }

    /** Whether [file] exists. */
    fun exists(file: Path): Boolean = SystemFileSystem.exists(file)

    /** Writes [text] to [file], making its directory first. */
    fun write(file: Path, text: String) {
        file.parent?.let { SystemFileSystem.createDirectories(it) }
        SystemFileSystem.sink(file).buffered().use { it.writeString(text) }
    }

    /** Deletes [file]. */
    fun delete(file: Path) {
        SystemFileSystem.delete(file)
    }

    private fun list(dir: Path): List<Path> = when (SystemFileSystem.metadataOrNull(dir)?.isDirectory) {
        true -> SystemFileSystem.list(dir).toList()
        else -> emptyList()
    }
}
