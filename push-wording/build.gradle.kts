import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// Every notification's wording (iPhone phase 4 part C; docs/superpowers/specs/
// 2026-11-17-iphone-phase-4c-pushes-design.md §7.1): the pushes', the chat cards' push text, the
// event reminder's, the child support reminder's and the request reminder's. The Android app depends
// on it, and on the iPhone it is a framework of its own, `PushWording`, which only the Notification
// Service Extension links: the extension has a small memory budget and carries neither Compose nor
// the data layer, so this module depends on no other module of ours and on no library.
//
// Its strings reach it through `WordingStrings`: on Android the app's own resources (the copy the
// app's `stringsToAndroidRes` generates from `:shared-ui`'s XML), on the iPhone the `.strings` and
// `.stringsdict` files `tools/ios/generate-push-strings.js` writes from the same XML for the keys
// `push-keys.txt` lists. The XML stays the one source.
//
// Built like `:shared`: AGP 9's Android KMP library target (`kotlin { android { } }`) and the two
// iPhone targets.
plugins {
    id("org.jetbrains.kotlin.multiplatform")
    id("com.android.kotlin.multiplatform.library")
    id("io.gitlab.arturbosch.detekt")
    id("org.jetbrains.kotlinx.kover")
}

/**
 * The iPhone's strings for the simulator tests (`PushWordingIosTest`): `tools/ios/generate-push-strings.js`
 * writes `<lang>.lproj/PushStrings.strings|.stringsdict` for the keys of `push-keys.txt` from
 * `:shared-ui`'s XML, as the notification extension's build does, into a directory the tests open as
 * a bundle. Node runs only before the simulator tests (the hosted macOS runner has it); compiling
 * the tests needs only the location below, so the Linux `shared` job runs no Node.
 */
val pushStringsForTests = layout.buildDirectory.dir("generated/pushStrings/bundle")
val generatePushStringsForTests = tasks.register<Exec>("generatePushStringsForTests") {
    val script = rootDir.resolve("tools/ios/generate-push-strings.js")
    val keys = file("push-keys.txt")
    val output = pushStringsForTests.get().asFile
    inputs.file(script)
    inputs.file(keys)
    inputs.dir(rootDir.resolve("shared-ui/src/commonMain/composeResources"))
    outputs.dir(output)
    commandLine("node", script.absolutePath, output.absolutePath, "--keys", keys.absolutePath)
}

/**
 * `PushStringsLocation`, the simulator tests' one input from the build: the directory above as an
 * absolute path (the simulator's test process reads the host's files by it), as `:shared-data`'s
 * `WireFixtureLocation` hands its tests their fixtures.
 */
val generatePushStringsLocation = tasks.register("generatePushStringsLocation") {
    val directory = pushStringsForTests.get().asFile.absolutePath
    val output = layout.buildDirectory.dir("generated/pushStringsLocation/iosTest/kotlin")
    inputs.property("directory", directory)
    outputs.dir(output)
    doLast {
        val escaped = directory.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\${'$'}")
        val file = output.get().file("com/coparently/app/pushwording/PushStringsLocation.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.coparently.app.pushwording
            |
            |/** Written by `:push-wording:generatePushStringsLocation`; see `push-wording/build.gradle.kts`. */
            |internal object PushStringsLocation {
            |    /** The directory holding `<lang>.lproj/PushStrings.*`, absolute. */
            |    const val DIR: String = "$escaped"
            |}
            |
            """.trimMargin()
        )
    }
}

