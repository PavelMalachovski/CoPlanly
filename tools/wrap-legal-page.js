#!/usr/bin/env node
// Wraps a rendered legal document into the self-contained page `web/` serves (REL-4).
//
// Reads an HTML fragment on stdin — `marked` output for one of the `docs/legal/*.md` files — and
// prints a complete page in the same one-file style as `web/delete-account/index.html`: no
// external CSS, fonts, scripts or images, so it is hostable on anything and cannot fail because
// a CDN did. Usage, from the repository root:
//
//   npx marked docs/legal/PRIVACY-POLICY.md   | node tools/wrap-legal-page.js privacy > web/privacy/index.html
//   npx marked docs/legal/TERMS-OF-SERVICE.md | node tools/wrap-legal-page.js terms   > web/terms/index.html
//
// The markdown is the source of truth; edit it, not the generated page, and regenerate both
// pages in the same commit. A page whose body still carries a `{{PLACEHOLDER}}` gets a banner
// saying it is a draft: `web/README.md` lists what has to be filled in before hosting.
//
// No dependencies on purpose — the same constraint as `tools/check-invariants.js` — so it runs
// wherever Node does.
'use strict';

const PAGES = {
  privacy: {
    title: 'CoPlanly — Privacy Policy',
    description: 'How CoPlanly handles the personal data of separated parents and their children.',
  },
  terms: {
    title: 'CoPlanly — Terms of Service',
    description: 'The terms under which CoPlanly, a shared calendar for co-parents, is offered.',
  },
};

const which = process.argv[2];
const page = PAGES[which];
if (!page) {
  process.stderr.write(`usage: wrap-legal-page.js <${Object.keys(PAGES).join('|')}> < body.html\n`);
  process.exit(2);
}

const chunks = [];
process.stdin.on('data', (chunk) => chunks.push(chunk));
process.stdin.on('end', () => {
  const body = Buffer.concat(chunks).toString('utf8').trim();
  if (!body) {
    process.stderr.write('wrap-legal-page.js: empty body on stdin\n');
    process.exit(2);
  }
  const placeholders = [...new Set(body.match(/\{\{[A-Z_]+\}\}/g) || [])].sort();
  process.stdout.write(render(page, body, placeholders));
});

/**
 * @param {{title: string, description: string}} meta What the page is.
 * @param {string} body The rendered document.
 * @param {!Array<string>} placeholders Every `{{PLACEHOLDER}}` still in it.
 * @return {string} The complete page.
 */
function render(meta, body, placeholders) {
  const draft = placeholders.length === 0 ? '' : `
<div class="draft" role="note">
  <p><strong>Draft.</strong> This page has not been reviewed by a lawyer and is not in force.
    Placeholders still to be filled in: ${placeholders.map((p) => `<code>${escape(p)}</code>`).join(', ')}.</p>
</div>
`;
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(meta.title)}</title>
<meta name="description" content="${escape(meta.description)}">
<!--
  Generated by tools/wrap-legal-page.js from docs/legal/ — edit the markdown, not this file, and
  regenerate. Self-contained on purpose: see web/README.md.
-->
<style>
  :root {
    color-scheme: light dark;
    --bg: #ffffff;
    --fg: #1b1b21;
    --muted: #55555f;
    --rule: #e2e2e8;
    --accent: #4f46b8;
    --warn-bg: #fdf3f3;
    --warn-fg: #7a2020;
    --quote-bg: #f4f3fb;
  }
  @media (prefers-color-scheme: dark) {
    :root {
      --bg: #1b1b21;
      --fg: #ecebf0;
      --muted: #a9a8b3;
      --rule: #33333c;
      --accent: #c2c1ff;
      --warn-bg: #3a2224;
      --warn-fg: #ffb4ab;
      --quote-bg: #26262e;
    }
  }
  * { box-sizing: border-box; }
  body {
    margin: 0;
    padding: 2rem 1.25rem 4rem;
    background: var(--bg);
    color: var(--fg);
    font: 16px/1.65 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
  }
  main { max-width: 42rem; margin: 0 auto; }
  h1 { font-size: 1.6rem; line-height: 1.25; margin: 0 0 1rem; }
  h2 { font-size: 1.2rem; margin: 2.5rem 0 .5rem; }
  h3 { font-size: 1rem; margin: 1.5rem 0 .25rem; }
  p, ul, ol { margin: .5rem 0; }
  ul, ol { padding-left: 1.25rem; }
  li { margin: .3rem 0; }
  a { color: var(--accent); }
  hr { border: 0; border-top: 1px solid var(--rule); margin: 3rem 0; }
  blockquote {
    margin: 1.25rem 0;
    padding: .9rem 1.1rem;
    background: var(--quote-bg);
    border-left: 3px solid var(--accent);
    border-radius: .25rem;
  }
  blockquote p { margin: .35rem 0; }
  .draft {
    background: var(--warn-bg);
    color: var(--warn-fg);
    border-radius: .5rem;
    padding: .9rem 1.1rem;
    margin: 0 0 1.5rem;
  }
  .draft p { margin: 0; }
  table { border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: .95em; }
  th, td { text-align: left; vertical-align: top; padding: .45rem .6rem; border-bottom: 1px solid var(--rule); }
  th { color: var(--muted); font-weight: 600; }
  .table-wrap { overflow-x: auto; }
  code {
    font-family: ui-monospace, SFMono-Regular, Menlo, Consolas, monospace;
    font-size: .9em;
  }
  footer { color: var(--muted); font-size: .875rem; margin-top: 3rem; }
</style>
</head>
<body>
<main>
${draft}
${body.replace(/<table>/g, '<div class="table-wrap"><table>').replace(/<\/table>/g, '</table></div>')}

<footer>
  <p><a href="../delete-account/">Delete your account</a> · <a href="../privacy/">Privacy policy</a> · <a href="../terms/">Terms of service</a></p>
</footer>
</main>
</body>
</html>
`;
}

/**
 * @param {string} text Raw text.
 * @return {string} The text with HTML metacharacters escaped.
 */
function escape(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
